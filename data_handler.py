# --- Emoji & Text Cleaning ---
class BasicTextCleaner:
    def clean(self, text):
        """Cleans text, including converting emojis to text descriptions."""
        text = str(text) # Ensure text is string

        # 1. Convert emojis to colon-delimited text descriptions (e.g., ":smiling_face:")
        # Ensure we handle potential errors or None values from emoji lib
        try:
            # Using lang='en' for consistent English descriptions
            demojized_text = emoji.demojize(text, language='en')
        except Exception as e:
            # Fallback to original text if demojization fails
            # print(f"Warning: Error during emoji demojization for text: '{text[:50]}...'. Error: {e}. Skipping demojization.")
            demojized_text = text # Fallback

        # 2. Lowercase the entire text
        text = demojized_text.lower()

        # 3. Process the demojized descriptions: remove colons and replace underscores with spaces.
        # This targets the pattern like :word_word: resulting from step 1 using regex.
        def replace_emoji_description(match):
            # match.group(1) is the content inside colons like "smiling_face_with_smiling_eyes"
            description = match.group(1).replace('_', ' ') # Replace underscores with spaces
            return description

        # Find all occurrences of :...: and replace them using the helper function
        # This is safer as it only processes patterns generated by demojize
        # Use re.IGNORECASE for case-insensitive matching if demojize output varies
        text_processed_emojis = re.sub(r':([a-zA-Z0-9_]+):', replace_emoji_description, text)


        # 4. Remove specific patterns (mentions, urls)
        text_no_mentions_urls = re.sub(r'@\w+', '', text_processed_emojis)
        text_no_mentions_urls = re.sub(r'http\S+|www\S+|https\S+', '', text_no_mentions_urls, flags=re.MULTILINE)


        # 5. Clean up extra whitespace (important after replacements and removals)
        text_cleaned = re.sub(r'\s+', ' ', text_no_mentions_urls).strip()

        return text_cleaned

    def preprocess_batch(self, texts):
        """Applies cleaning to a batch of texts with a progress bar."""
        # Use a list comprehension for efficiency, tqdm will wrap it
        return [self.clean(text) for text in tqdm(texts, desc="Cleaning Text")]

